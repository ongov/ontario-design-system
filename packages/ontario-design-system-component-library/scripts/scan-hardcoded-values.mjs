#!/usr/bin/env node
// @ts-check
/**
 * scan-hardcoded-values.mjs
 *
 * Inventories hard-coded colour (hex) and pixel (px) literals in the component
 * library SCSS sources. This is the Phase 0 (DS-2686) baseline map for the
 * design-token migration: it tells the upcoming Component layer work which raw
 * values still need to be replaced with tokens.
 *
 * What it flags: any `#rgb` / `#rrggbb` / `#rrggbbaa` colour literal, and any
 * `<number>px` length literal, that appears in SCSS source after comments are
 * stripped. Token *references* (e.g. `colours.$ontario-greyscale-70`) contain
 * no literal, so they are correctly ignored.
 *
 * What it does NOT do: decide whether a literal is legitimate (some px values —
 * SVG stroke offsets, hairline outlines — are genuinely raw). It is an
 * inventory for humans to triage, not a pass/fail gate. It can later graduate
 * into a CI ratchet ("no new hard-coded values") for the Component Epic.
 *
 * Output is deterministic (sorted) so re-running produces a byte-identical
 * report.
 *
 * Usage:
 *   node scripts/scan-hardcoded-values.mjs            # write the report
 *   node scripts/scan-hardcoded-values.mjs --check    # fail if report is stale
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, sep } from 'node:path';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageRoot = join(scriptDir, '..');
const scanRoot = join(packageRoot, 'src');
const reportPath = join(scriptDir, 'hardcoded-values-report.md');

const HEX_RE = /#[0-9a-fA-F]{3,8}\b/g;
const PX_RE = /-?\d*\.?\d+px\b/g;

/** Recursively collect all .scss files under a directory, sorted. */
function collectScssFiles(dir) {
	/** @type {string[]} */
	const files = [];
	for (const entry of readdirSync(dir).sort()) {
		const full = join(dir, entry);
		const stats = statSync(full);
		if (stats.isDirectory()) {
			files.push(...collectScssFiles(full));
		} else if (entry.endsWith('.scss')) {
			files.push(full);
		}
	}
	return files;
}

/** Remove // line comments and block comments so literals inside them are ignored. */
function stripComments(source) {
	// Block comments first, preserving newlines so line numbers stay accurate.
	const withoutBlocks = source.replace(/\/\*[\s\S]*?\*\//g, (match) => match.replace(/[^\n]/g, ' '));
	// Then // line comments.
	return withoutBlocks
		.split('\n')
		.map((line) => {
			const idx = line.indexOf('//');
			return idx === -1 ? line : line.slice(0, idx);
		})
		.join('\n');
}

/**
 * @param {string} file
 * @returns {{ file: string, line: number, kind: 'hex' | 'px', value: string }[]}
 */
function scanFile(file) {
	const raw = readFileSync(file, 'utf8');
	const cleaned = stripComments(raw);
	const lines = cleaned.split('\n');
	const findings = [];
	lines.forEach((line, i) => {
		for (const match of line.matchAll(HEX_RE)) {
			findings.push({ file, line: i + 1, kind: 'hex', value: match[0] });
		}
		for (const match of line.matchAll(PX_RE)) {
			findings.push({ file, line: i + 1, kind: 'px', value: match[0] });
		}
	});
	return findings;
}

function buildReport(findings) {
	const hexCount = findings.filter((f) => f.kind === 'hex').length;
	const pxCount = findings.filter((f) => f.kind === 'px').length;
	const fileCount = new Set(findings.map((f) => f.file)).size;

	const lines = [];
	lines.push('# Hard-coded value inventory — component library SCSS');
	lines.push('');
	lines.push('> Generated by `scripts/scan-hardcoded-values.mjs`. Do not edit by hand —');
	lines.push('> re-run the script to refresh. This is the Phase 0 (DS-2686) map of raw');
	lines.push('> colour (hex) and pixel (px) literals that the Component layer work will');
	lines.push('> replace with design tokens. Some px literals are legitimately raw (e.g.');
	lines.push('> SVG stroke offsets); this inventory is for triage, not a pass/fail gate.');
	lines.push('');
	lines.push('## Summary');
	lines.push('');
	lines.push(`- **${hexCount}** hard-coded hex colour literal(s)`);
	lines.push(`- **${pxCount}** hard-coded \`px\` length literal(s)`);
	lines.push(`- across **${fileCount}** file(s)`);
	lines.push('');
	lines.push('## Findings');
	lines.push('');

	if (findings.length === 0) {
		lines.push('_No hard-coded hex or px literals found._');
		lines.push('');
		return lines.join('\n');
	}

	/** @type {Map<string, typeof findings>} */
	const byFile = new Map();
	for (const finding of findings) {
		const rel = relative(packageRoot, finding.file).split(sep).join('/');
		if (!byFile.has(rel)) byFile.set(rel, []);
		byFile.get(rel).push(finding);
	}

	for (const rel of [...byFile.keys()].sort()) {
		lines.push(`### ${rel}`);
		lines.push('');
		lines.push('| Line | Kind | Value |');
		lines.push('| --- | --- | --- |');
		const rows = byFile
			.get(rel)
			.slice()
			.sort((a, b) => a.line - b.line || a.kind.localeCompare(b.kind) || a.value.localeCompare(b.value));
		for (const row of rows) {
			lines.push(`| ${row.line} | ${row.kind} | \`${row.value}\` |`);
		}
		lines.push('');
	}

	return lines.join('\n');
}

const checkMode = process.argv.includes('--check');

const findings = collectScssFiles(scanRoot).flatMap(scanFile);
const report = buildReport(findings);

if (checkMode) {
	let existing = '';
	try {
		existing = readFileSync(reportPath, 'utf8');
	} catch {
		existing = '';
	}
	if (existing !== report) {
		console.error('Hard-coded value report is out of date. Run: node scripts/scan-hardcoded-values.mjs');
		process.exit(1);
	}
	console.log('Hard-coded value report is up to date.');
} else {
	writeFileSync(reportPath, report);
	const hexCount = findings.filter((f) => f.kind === 'hex').length;
	const pxCount = findings.filter((f) => f.kind === 'px').length;
	console.log(`Wrote ${relative(packageRoot, reportPath).split(sep).join('/')}: ${hexCount} hex, ${pxCount} px.`);
}
